// Step 6: compare this run with the previous one (BUILD_BRIEF §7), after all collectors have run.
//   - careers-page roles without a stable id: a "new" role + a role gone this run with the same
//     function/country/seniority and a similar title are one renamed job (keep the old row and its first_seen)
//   - reposts: roles that look new but aren't get is_repost = 1 (scoring ignores them as "new")
// Usage: npx tsx scripts/compare.ts [--remote] [--date YYYY-MM-DD]
import { mkdir, writeFile } from "node:fs/promises";
import { isRepost, matchRenamed, type JobRow } from "../src/lib/compare.ts";
import { d1ExecFile, d1Query, sq } from "../src/lib/d1.ts";

const args = process.argv.slice(2);
const remote = args.includes("--remote");
const runDate = args.includes("--date") ? args[args.indexOf("--date") + 1] : new Date().toISOString().slice(0, 10);

const cols = "id, company_id, source, source_job_id, title, function, seniority, country, posted_date, first_seen, last_seen, is_open, is_baseline";
type Row = JobRow & { company_id: number; is_baseline: number };

const prevRuns = new Map(
  d1Query<{ company_id: number; prev: string | null }>(
    `SELECT company_id, MAX(run_date) AS prev FROM snapshots WHERE is_dummy = 0 AND run_date < ${sq(runDate)} GROUP BY company_id`, remote,
  ).map((r) => [r.company_id, r.prev]),
);
const fresh = d1Query<Row>(`SELECT ${cols} FROM jobs WHERE is_dummy = 0 AND first_seen = ${sq(runDate)}`, remote);
const closed = d1Query<Row>(`SELECT ${cols} FROM jobs WHERE is_dummy = 0 AND is_open = 0`, remote);

const sql: string[] = [`-- compare ${runDate} (generated by scripts/compare.ts)`];
let renamed = 0;
let reposts = 0;
const byCompany = new Map<number, Row[]>();
for (const j of fresh) byCompany.set(j.company_id, [...(byCompany.get(j.company_id) ?? []), j]);

for (const [cid, newRows] of byCompany) {
  const prev = prevRuns.get(cid) ?? null;
  if (!prev) continue; // first real run for this company: everything is a first sighting, nothing to compare
  const closedHere = closed.filter((o) => o.company_id === cid);
  const goneThisRun = closedHere.filter((o) => o.last_seen === prev);

  const pairs = matchRenamed(newRows, goneThisRun);
  const merged = new Set<number>();
  for (const [n, o] of pairs) {
    merged.add(n.id);
    renamed++;
    // Keep the old row (and its first_seen); take the new title and id so the next run matches by id.
    sql.push(`DELETE FROM jobs WHERE id = ${n.id};`);
    sql.push(`UPDATE jobs SET title = ${sq(n.title)}, source_job_id = ${sq(n.source_job_id)}, last_seen = ${sq(runDate)}, is_open = 1 WHERE id = ${o.id};`);
  }
  for (const n of newRows) {
    if (merged.has(n.id) || n.is_baseline) continue;
    if (isRepost(n, prev, closedHere)) { reposts++; sql.push(`UPDATE jobs SET is_repost = 1 WHERE id = ${n.id};`); }
  }
}

if (sql.length > 1) {
  await mkdir("data/runs", { recursive: true });
  const path = `data/runs/compare-${runDate}.sql`;
  await writeFile(path, sql.join("\n") + "\n");
  d1ExecFile(path, remote);
}
const compared = [...byCompany.keys()].filter((c) => prevRuns.get(c)).length;
console.log(`compare ${runDate}: ${fresh.length} jobs first seen this run · ${compared} companies had a previous run · ${renamed} renamed roles merged · ${reposts} reposts flagged`);
process.exit(0);
