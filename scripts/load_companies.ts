// Step 2: load the company list into D1.
// Merges data/companies.csv + data/company_domains.csv + data/job_sources.json (step 1) + fit tags (§8),
// writes data/seed/companies.sql and runs it with wrangler. Upserts on domain, so it is safe to re-run.
// Usage: npx tsx scripts/load_companies.ts            -> local D1 (default)
//        npx tsx scripts/load_companies.ts --remote   -> deployed D1 (needs `wrangler login`)
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { parseCsv } from "../src/lib/csv.ts";
import { computeFit, type CompanyInput } from "../src/lib/fit.ts";

const remote = process.argv.includes("--remote");
const today = new Date();

const companies = parseCsv(await readFile("data/companies.csv", "utf8"));
const domains = new Map(parseCsv(await readFile("data/company_domains.csv", "utf8")).map((r) => [r.company, r.domain]));
// HQ country per company (default IL: the list is Israeli-founded companies). Used for "new market entry".
const hqOverrides = new Map(parseCsv(await readFile("data/company_hq.csv", "utf8")).map((r) => [r.company, r.hq_country]));
const sources = new Map(
  (JSON.parse(await readFile("data/job_sources.json", "utf8")) as Record<string, string>[]).map((r) => [r.company, r]),
);

const q = (v: string | number | null | undefined) =>
  v === null || v === undefined || v === "" ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const monthToDate = (ym?: string) => (ym ? `${ym}-01` : undefined);

function greenfield(status: string): { status: "open" | "portfolio" | "conflict"; note: string } {
  if (/^portfolio/i.test(status)) return { status: "portfolio", note: status.replace(/^portfolio\s*-\s*/i, "") };
  if (/possible conflict/i.test(status)) return { status: "conflict", note: status.replace(/^possible conflict\s*-\s*/i, "") };
  return { status: "open", note: "" };
}

// Comeet job_source_url from step 1 shows "token=<from careers page>": keep it that way; the token is never stored.
const problems: string[] = [];
const rows = companies.map((c) => {
  const domain = domains.get(c.Company) ?? c.Website;
  if (!domain) problems.push(`no domain for ${c.Company}`);
  const s = sources.get(c.Company);
  if (!s) problems.push(`no step-1 job source for ${c.Company}`);
  const fit = computeFit(c as unknown as CompanyInput, today);
  const gf = greenfield(c["Greenfield status"] ?? "");
  return {
    list_no: Number(c["#"]) || null,
    name: c.Company,
    domain,
    hq: hqOverrides.get(c.Company) ?? "IL",
    category: c["Greenfield category"],
    sector: c.Sector,
    last_round: c["Latest round"],
    round_amount: c["Amount ($M)"],
    round_closed: monthToDate(fit.roundClosed),
    round_announced: monthToDate(fit.roundAnnounced),
    greenfield_status: gf.status,
    greenfield_note: gf.note,
    fit_tag: fit.tag,
    fit_visibility: fit.visibility,
    fit_reason: [fit.reason, ...fit.flags].join("; "),
    role_in_list: c["Role in the list"],
    why_included: c["Why included"],
    job_source_type: s?.job_source_type ?? "none",
    job_source_url: s?.job_source_url,
    ats_slug: s?.ats_slug,
    careers_url: s?.careers_url,
    job_source_confidence: s?.confidence || null,
    needs_rendering: s?.needs_rendering === "yes" ? 1 : 0,
    job_source_notes: s?.notes,
  };
});
if (problems.length) throw new Error(`refusing to load:\n  ${problems.join("\n  ")}`);

const cols = Object.keys(rows[0]);
const updates = cols.filter((k) => k !== "domain").map((k) => `${k} = excluded.${k}`).concat("updated_at = datetime('now')");
const sql = [
  "-- Generated by scripts/load_companies.ts. Do not edit by hand.",
  ...rows.map((r) =>
    `INSERT INTO companies (${cols.join(", ")}) VALUES (${cols.map((k) => q((r as Record<string, string | number | null | undefined>)[k])).join(", ")})\n` +
    `  ON CONFLICT(domain) DO UPDATE SET ${updates.join(", ")};`),
  // Companies dropped from the list (e.g. the 11 Nov rebuild) are removed with their history.
  `DELETE FROM companies WHERE domain NOT IN (${rows.map((r) => q(r.domain)).join(", ")});`,
].join("\n") + "\n";

await mkdir("data/seed", { recursive: true });
await writeFile("data/seed/companies.sql", sql);
console.log(`wrote data/seed/companies.sql (${rows.length} companies)`);

execFileSync("npx", ["wrangler", "d1", "execute", "team-signals", remote ? "--remote" : "--local", "--file", "data/seed/companies.sql"], { stdio: "inherit" });
