// Step 6: dummy history (BUILD_BRIEF §12). For companies with NO real snapshot before today, create 3 past
// snapshots (90, 60 and 30 days ago) with is_dummy = 1, so trend signals and "change vs last run" have
// something to compare against until real runs accumulate. Clearly labelled; never mixed with real data:
// real snapshots keep is_dummy = 0, and every signal computed from dummy history is marked dummy.
// Deterministic per company (same numbers on every run). Re-running replaces the dummy rows.
// Usage: npx tsx scripts/seed_dummy_history.ts [--remote] [--clear]
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { d1ExecFile, d1Query, sq } from "../src/lib/d1.ts";

const args = process.argv.slice(2);
const remote = args.includes("--remote");
const clearOnly = args.includes("--clear");
const today = new Date().toISOString().slice(0, 10);
const daysAgo = (n: number) => { const d = new Date(`${today}T00:00:00Z`); d.setUTCDate(d.getUTCDate() - n); return d.toISOString().slice(0, 10); };

/** Deterministic pseudo-random in [0,1) from a string. */
const rand = (s: string) => parseInt(createHash("sha256").update(s).digest("hex").slice(0, 8), 16) / 0x100000000;

const sql: string[] = [`-- dummy history ${today} (generated by scripts/seed_dummy_history.ts)`, "DELETE FROM snapshots WHERE is_dummy = 1;"];
let seeded = 0;
if (!clearOnly) {
  const rows = d1Query<{ id: number; name: string; open_now: number | null; has_real_history: number; coverage: string | null }>(
    `SELECT c.id, c.name,
            (SELECT open_jobs FROM snapshots s WHERE s.company_id = c.id AND s.is_dummy = 0 ORDER BY run_date DESC LIMIT 1) AS open_now,
            EXISTS (SELECT 1 FROM snapshots s WHERE s.company_id = c.id AND s.is_dummy = 0 AND s.run_date < ${sq(today)}) AS has_real_history,
            (SELECT coverage FROM snapshots s WHERE s.company_id = c.id AND s.is_dummy = 0 ORDER BY run_date DESC LIMIT 1) AS coverage
       FROM companies c`, remote,
  );
  for (const c of rows) {
    if (c.has_real_history) continue; // brief: dummy only where no real history exists
    // A plausible path to today's count: each company gets its own trend between -40% and +40% over 90 days.
    const now = c.open_now;
    const trend = (rand(`${c.name}:trend`) - 0.5) * 0.8;
    for (const [i, ago] of [[0, 90], [1, 60], [2, 30]] as const) {
      const fraction = (3 - i) / 3; // 90d ago = full distance from today, 30d ago = a third
      const noise = 1 + (rand(`${c.name}:${ago}`) - 0.5) * 0.1;
      const open = now === null ? null : Math.max(0, Math.round((now / (1 + trend)) * (1 + trend * (1 - fraction)) * noise));
      sql.push(`INSERT INTO snapshots (company_id, run_date, sources_checked, coverage, open_jobs, is_dummy) VALUES (${c.id}, ${sq(daysAgo(ago))}, ${sq(JSON.stringify({ dummy: "seeded" }))}, ${sq(c.coverage ?? "low")}, ${open === null ? "NULL" : open}, 1)
  ON CONFLICT(company_id, run_date, is_dummy) DO UPDATE SET open_jobs = excluded.open_jobs, coverage = excluded.coverage;`);
    }
    seeded++;
  }
}
await mkdir("data/runs", { recursive: true });
const path = `data/runs/dummy-history-${today}.sql`;
await writeFile(path, sql.join("\n") + "\n");
d1ExecFile(path, remote);
console.log(clearOnly ? "dummy history cleared" : `dummy history: ${seeded} companies × 3 past snapshots (90/60/30 days ago), is_dummy = 1`);
process.exit(0);
